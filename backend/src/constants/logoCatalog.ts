function normalizeName(name: string): string {
  return (name || '')
    .toLowerCase()
    .trim()
    .replace(/[.'"]/g, '')
    .replace(/\s+/g, ' ');
}

export function resolveTeamLogoUrl(teamName: string, fallbackUrl?: string): string {
  const norm = normalizeName(teamName);
  if (TEAM_LOGO_MAP[norm]) {
    return TEAM_LOGO_MAP[norm];
  }

  // Check partial match
  for (const [key, url] of Object.entries(TEAM_LOGO_MAP)) {
    if (norm.includes(key) || key.includes(norm)) {
      return url;
    }
  }

  // If a valid image URL was passed from AI and it is NOT an SVG (PNG/JPG only)
  if (fallbackUrl && typeof fallbackUrl === 'string' && (fallbackUrl.startsWith('http://') || fallbackUrl.startsWith('https://')) && !fallbackUrl.endsWith('.svg')) {
    return fallbackUrl;
  }

  // Reliable dynamic PNG badge fallback
  const initials = (teamName || 'FC')
    .split(' ')
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0].toUpperCase())
    .join('');
  return `https://ui-avatars.com/api/?name=${encodeURIComponent(initials || 'FC')}&background=1e293b&color=38bdf8&bold=true&rounded=true&format=png`;
}

export function resolveCompetitionLogoUrl(competition: string, fallbackUrl?: string): string {
  const norm = normalizeName(competition);
  if (COMPETITION_LOGO_MAP[norm]) {
    return COMPETITION_LOGO_MAP[norm];
  }

  for (const [key, url] of Object.entries(COMPETITION_LOGO_MAP)) {
    if (norm.includes(key) || key.includes(norm)) {
      return url;
    }
  }

  if (fallbackUrl && typeof fallbackUrl === 'string' && (fallbackUrl.startsWith('http://') || fallbackUrl.startsWith('https://')) && !fallbackUrl.endsWith('.svg')) {
    return fallbackUrl;
  }

  return 'https://images.fotmob.com/image_resources/logo/leaguelogo/47.png';
}
